def specialist_brief(role: str) -> str:
    """Resolve a single explicit role without guessing when several specialisms match."""
    text = role.casefold().replace("ё", "е")
    found = [profile for profile in PROFILES.values()
             if any(alias.replace("ё", "е") in text for alias in profile["aliases"])]
    return found[0]["brief"] if len(found) == 1 else ""
